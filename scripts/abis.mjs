// Regenerates src/abis.ts from a built checkout of https://github.com/Awesomechain/Contracts.
// Usage: node scripts/abis.mjs ../Contracts   (run `forge build` there first)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? "../Contracts";
const read = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;
const merge = (...abis) => {
  const seen = new Set();
  return abis.flat().filter((x) => {
    const k = `${x.type}:${x.name ?? ""}:${(x.inputs ?? []).map((i) => i.type).join(",")}`;
    return seen.has(k) ? false : (seen.add(k), true);
  });
};
const out = {
  awesomeFactoryAbi: read("AwesomeFactory"),
  awesomeRouterAbi: read("AwesomeRouter"),
  awesomeUniRouterAbi: read("AwesomeUniRouter"),
  awesomeTokenAbi: read("AwesomeToken"),
  feeVaultAbi: merge(read("PcsFeeVault"), read("UniFeeVault")),
  hookAbi: merge(read("PcsHook"), read("UniHook")),
  lockerAbi: merge(read("PcsLocker"), read("UniLocker")),
  pairRegistryAbi: read("PairRegistry"),
};
let ts = "// Generated by scripts/abis.mjs from Awesomechain/Contracts v1.1.0. Do not edit.\n\n";
for (const [k, v] of Object.entries(out)) ts += `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n\n`;
writeFileSync("src/abis.ts", ts);
console.log("wrote src/abis.ts:", Object.keys(out).join(", "));
